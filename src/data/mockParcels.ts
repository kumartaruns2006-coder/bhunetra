// Helper to generate realistic contiguous polygon coordinates around a center point
const generatePolygon = (centerLat: number, centerLng: number, sizeLat = 0.0018, sizeLng = 0.0022): [number, number][] => {
  const halfLat = sizeLat / 2;
  const halfLng = sizeLng / 2;
  return [
    [Number((centerLat - halfLat).toFixed(5)), Number((centerLng - halfLng).toFixed(5))],
    [Number((centerLat + halfLat).toFixed(5)), Number((centerLng - halfLng * 0.9).toFixed(5))],
    [Number((centerLat + halfLat * 1.1).toFixed(5)), Number((centerLng + halfLng).toFixed(5))],
    [Number((centerLat - halfLat * 0.9).toFixed(5)), Number((centerLng + halfLng * 1.1).toFixed(5))],
    [Number((centerLat - halfLat).toFixed(5)), Number((centerLng - halfLng).toFixed(5))] // closed
  ];
};

